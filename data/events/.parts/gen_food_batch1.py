def set_acc(items):
    """把人为指定的月/年级精度写回（宪法：只升不降，绝不猜）"""
    acc_map = {
        "1986-01-01": "year", "1990-01-01": "year", "1992-01-01": "year",
        "1995-01-01": "year", "1996-01-01": "year", "1998-05-01": "month",
        "1999-01-01": "month", "2000-03-01": "month",
    }
    for it in items:
        if it["id"][:10] in acc_map:
            it["date_accuracy"] = acc_map[it["id"][:10]]
    return items

