#!/usr/bin/env python3
# -*- coding: utf-8 -*-
# 维基原始语料过滤器：对 data/wiki_raw/ 做敏感筛查，产出候选池
# 用法: python3 scripts/wiki_filter.py
# 产出: data/wiki_raw/candidates.json —— {year: [ {date, text, safe, block} ]}，按日期排序
# 原则：黑名单（敏感）一票否决 + 白名单（安全领域）放行；两清都不中的标记 needs_review 由人工读。
#       宁可漏收、不可错收；候选池只在本地，不入库、不部署。
import json, os, re, glob

RAW = 'data/wiki_raw'
BLOCK_KW = [
    # 政治与人事
    '党','人大','政协','国务院','总理','部长','主席','书记','会议','闭幕','开幕会','会见','访问',
    '换届','当选','任命','免职','视察','批示','讲话','文件','意见','决定','条例','办法（','征求意见',
    '台','香港','澳门','新疆','西藏独立','主权','领土','抗议','示威','游行','罢工','罢课','制裁',
    '签证','外交','领事','间谍','气球','军演','军队','武警','警察','公安','法院','检察院','判决',
    '刑','逮捕','拘留','被查','被抓','被捕','被拘','处分','通报','反腐','双规','落马',
    # 刑案与伤亡
    '案','杀','刺','凶','伤人','跳','坠','爆炸','火','塌','淹','中毒','失联','身亡','死亡','遇难',
    '地震','洪水','暴雨','山洪','泥石流','台风','灾害','事故','空难','枪','砍','劫','绑架','诈骗',
    '性侵','骚扰','霸凌','网暴','自杀','轻生','抑郁','遗体','尸',
    # 疫情与公共卫生事件
    '疫情','病毒','感染','确诊','封控','隔离','核酸','方舱','阳性','疫苗事故',
    # 维权与社会风波
    '维权','烂尾','欠薪','讨薪','裁员','拖欠','讨说法','退钱','赔偿纠纷','原告','被告','起诉',
    # 国际时政（除非纯文化）
    '美国','日本','韩国','朝鲜','俄罗斯','乌克兰','印度','菲律宾','越南','缅甸','以色列','巴勒斯坦',
    '伊朗','北约','欧盟','联合国','G7','峰会公报',
]
SAFE_KW = [
    # 科技/互联网
    '互联网','上线','发布','开通','app','App','APP','AI','人工智能','大模型','芯片','量子','超导',
    '机器人','5G','6G','卫星','火箭','发射','飞船','空间站','航天','嫦娥','天问','北斗','首飞','试飞',
    '专利','研发',' breakthrough','突破','世界纪录','首例','首个','首艘','首条','首款','超级计算机',
    # 游戏/文娱
    '游戏','电竞','冠军','夺冠','Steam','手游','网游','主机','发售','公测','内测','票房','上映',
    '开播','首播','定档','演唱会','专辑','金曲','动漫','漫画','追番','小说','作家','茅盾','诺奖','图灵',
    # 体育
    '奥运','亚运','冬奥','世界杯','世乒赛','苏迪曼','汤姆斯','尤伯','世锦赛','联赛','公开','大师赛',
    ' Marathon','马拉松','进球','比分','金','银','铜',
    # 经济/产业
    '产量','出口','吞吐','快递','销量','市值','上市','融资','投产','通车','机场','高铁','大桥','隧道',
    '电站','并网','深中','港珠澳','销售额','双十一','成交','破亿','行业','产业','博物馆','开馆','开园',
    '申遗','世界遗产','出土','文物','遗址','考古',
    # 社会民生（中性现象）
    '流行语','热词','走红','爆红','刷屏','出圈','烧烤','旅游','游客','假期','春运','返程','奶茶',
    '外卖','打卡','夜市','集市',' pet','宠物','猫','狗',
]

def scan(text):
    hits_s = [k for k in SAFE_KW if k in text]
    hits_b = [k for k in BLOCK_KW if k in text]
    return hits_s, hits_b

def mdate(text):
    m = re.match(r'^(\d{1,2})月(\d{1,2})日', text)
    return f'{m.group(1).zfill(2)}-{m.group(2).zfill(2)}' if m else ''

pool = {}
n_raw = n_cand = n_need = 0
for f in sorted(glob.glob(f'{RAW}/*.json')):
    name = os.path.basename(f)
    if not name[:-5].isdigit():
        continue
    year = int(name[:-5])
    items = json.load(open(f))
    cands = []
    for it in items:
        t = it['text']
        n_raw += 1
        hits_s, hits_b = scan(t)
        if hits_b:
            continue  # 黑名单一票否决
        if hits_s:
            cands.append({'date': mdate(t), 'text': t[:200], 'safe': hits_s[:6], 'tag': 'candidate'})
            n_cand += 1
        else:
            cands.append({'date': mdate(t), 'text': t[:200], 'safe': [], 'tag': 'needs_review'})
            n_need += 1
    cands.sort(key=lambda x: x['date'])
    pool[year] = cands

out = f'{RAW}/candidates.json'
json.dump(pool, open(out, 'w'), ensure_ascii=False, indent=1)
print(f'原始 {n_raw} 条 → 候选 {n_cand} 条 + 待人工 {n_need} 条 → {out}')
print('\n各年候选池：')
for y in sorted(pool, key=int):
    c = pool[y]
    cand = sum(1 for x in c if x['tag'] == 'candidate')
    need = len(c) - cand
    print(f'  {y}: 候选 {cand:3d} / 待人工 {need:3d}')
