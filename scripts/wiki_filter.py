#!/usr/bin/env python3
# -*- coding: utf-8 -*-
# 维基原始语料过滤器：对 data/wiki_raw/ 做敏感筛查，产出候选池
# 用法: python3 scripts/wiki_filter.py
# 产出: data/wiki_raw/candidates.json —— {year: [ {date, text, safe, block} ]}，按日期排序
#
# 政策（2026-10-22 修订）：
#   1) 政治领域（党政人事/外交/时政）——排除；
#   2) 刑案与暴力伤亡细节——排除；
#   3) 天灾、重大事故、疫情节点（非典/新冠等）——公正记录：文本含灾疫词时，
#      伤亡类软词不再一票否决，放行为 candidate（人工复核时保持客观措辞、不渲染细节）；
#   4) 正面领域（科技互联网/游戏文娱/体育/经济产业/文化考古/民生/人物荣誉/非遗）放行。
import json, os, re, glob

RAW = 'data/wiki_raw'

# 硬否决：政治/刑案/维权/国际时政。命中即排除，灾疫词也救不回。
BLOCK_KW = [
    # 政治与人事
    '党','人大','政协','国务院','总理','部长','主席','书记','会议','闭幕','开幕会','会见','访问',
    '换届','当选','任命','免职','视察','批示','讲话','文件','意见','决定','条例','办法（','征求意见',
    '台湾','香港','澳门','新疆','西藏','主权','领土','抗议','示威','游行','罢工','罢课','制裁',
    '签证','外交','领事','间谍','气球','军演','军队','武警','警察','公安','法院','检察院','判决',
    '逮捕','拘留','被查','被抓','被捕','被拘','处分','通报','反腐','双规','落马',
    # 刑案与暴力（区别于天灾伤亡）
    '杀','刺杀','凶杀','凶','枪击','砍','劫','绑架','诈骗','性侵','骚扰','霸凌','网暴','轻生','抑郁',
    # 维权与社会风波
    '维权','烂尾','欠薪','讨薪','裁员','拖欠','讨说法','退钱','赔偿纠纷','原告','被告','起诉',
    # 国际时政（除非纯文化）
    '美国','日本','韩国','朝鲜','俄罗斯','乌克兰','印度','菲律宾','越南','缅甸','以色列','巴勒斯坦',
    '伊朗','北约','欧盟','联合国','G7','峰会公报',
]

# 软否决：伤亡/疫情细节词。仅当文本同时含灾疫记录词（DISASTER_KW）时放行——
# 天灾/事故/疫情节点要求公正记录，伤亡数字是事实的一部分；但纯刑案/个人悲剧不放。
SOFT_KW = [
    '身亡','死亡','遇难','遗体','尸','自杀','爆炸','中毒','失联','跳楼','坍塌','塌方','溺亡',
    '疫情','病毒','感染','确诊','封控','隔离','核酸','方舱','阳性','疫苗事故','死亡人数',
]

# 灾疫记录词：命中且仅软词被命中时，条目放行为 candidate（公正记录类）
DISASTER_KW = [
    '地震','洪水','暴雨','山洪','泥石流','台风','寒潮','雪灾','旱灾','沙尘暴','灾害','灾',
    '事故','空难','海难','矿难','火灾','塌桥','沉船','疫情','非典','SARS','新冠','禽流感','猪瘟',
    '非洲猪瘟','霍乱','鼠疫','甲流','流感',
]

SAFE_KW = [
    # 科技/互联网
    '互联网','上线','发布','开通','app','App','APP','AI','人工智能','大模型','芯片','量子','超导',
    '机器人','5G','6G','卫星','火箭','发射','飞船','空间站','航天','嫦娥','天问','北斗','首飞','试飞',
    '专利','研发','突破','世界纪录','首例','首个','首艘','首条','首款','超级计算机',
    # 游戏/文娱
    '游戏','电竞','冠军','夺冠','Steam','手游','网游','主机','发售','公测','内测','票房','上映',
    '开播','首播','定档','演唱会','专辑','金曲','动漫','漫画','追番','小说','作家','茅盾','诺奖','图灵',
    # 体育
    '奥运','亚运','冬奥','世界杯','世乒赛','苏迪曼','汤姆斯','尤伯','世锦赛','联赛','公开','大师赛',
    '马拉松','进球','比分',
    # 经济/产业
    '产量','出口','吞吐','快递','销量','市值','上市','融资','投产','通车','机场','高铁','大桥','隧道',
    '电站','并网','深中','港珠澳','销售额','双十一','成交','破亿','行业','产业','博物馆','开馆','开园',
    '申遗','世界遗产','出土','文物','遗址','考古',
    # 社会民生（中性现象）
    '流行语','热词','走红','爆红','刷屏','出圈','烧烤','旅游','游客','假期','春运','返程','奶茶',
    '外卖','打卡','夜市','集市','宠物','猫','狗',
    # 人物荣誉 / 教育科学 / 地域发展（2026-10-22 新增方向）
    '感动中国','十大人物','杰出','贡献','表彰','荣誉','称号','劳模','先锋','人物评选','当选年度',
    '非遗','非物质文化遗产','人类非物质文化遗产','传承人','学校','大学','学院','开学','招生','扩招',
    '建市','设市','设区','撤县','新城区','开发区','特区','新区',' GDP','生产总值','扶贫','脱贫',
    '国家级','试验区','示范区','援建','通航','建站','落户',
]

def scan(text):
    hits_s = [k for k in SAFE_KW if k in text]
    hits_d = [k for k in DISASTER_KW if k in text]
    hits_soft = [k for k in SOFT_KW if k in text]
    hits_b = [k for k in BLOCK_KW if k in text]
    return hits_s, hits_d, hits_soft, hits_b

def mdate(text):
    m = re.match(r'^(\d{1,2})月(\d{1,2})日', text)
    return f'{m.group(1).zfill(2)}-{m.group(2).zfill(2)}' if m else ''

pool = {}
n_raw = n_cand = n_disaster = n_need = n_block = 0
for f in sorted(glob.glob(f'{RAW}/*.json')):
    name = os.path.basename(f)
    if not name[:-5].isdigit():
        continue
    year = int(name[:-5])
    items = json.load(open(f))
    cands = []
    for it in items:
        t = it['text']
        n_raw += 1
        hits_s, hits_d, hits_soft, hits_b = scan(t)
        if hits_b:
            n_block += 1
            continue  # 硬否决：政治/刑案/维权/国际时政
        if hits_soft and not hits_d:
            n_block += 1
            continue  # 软否决：纯伤亡/疫情细节且非灾疫记录节点
        if hits_s or hits_d:
            tag = 'disaster_ok' if hits_d else 'candidate'
            if hits_d:
                n_disaster += 1
            else:
                n_cand += 1
            cands.append({'date': mdate(t), 'text': t[:200],
                          'safe': (hits_s + hits_d)[:6], 'tag': tag})
        else:
            cands.append({'date': mdate(t), 'text': t[:200], 'safe': [], 'tag': 'needs_review'})
            n_need += 1
    cands.sort(key=lambda x: x['date'])
    pool[year] = cands

out = f'{RAW}/candidates.json'
json.dump(pool, open(out, 'w'), ensure_ascii=False, indent=1)
print(f'原始 {n_raw} 条 → 候选 {n_cand} + 灾疫公正记录 {n_disaster} + 待人工 {n_need}，排除 {n_block}')
print(f'→ {out}')
print('\n各年候选池（候选+灾疫）：')
for y in sorted(pool, key=int):
    c = pool[y]
    cand = sum(1 for x in c if x['tag'] in ('candidate', 'disaster_ok'))
    need = len(c) - cand
    print(f'  {y}: 候选 {cand:3d} / 待人工 {need:3d}')
