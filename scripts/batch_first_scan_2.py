BASE = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "data", "events")
buckets = {}
for e in E:
    buckets.setdefault(TARGET[e["id"]], []).append(e)
total_added = 0
for fname, items in sorted(buckets.items()):
    path = os.path.join(BASE, fname)
    db = json.load(open(path, encoding="utf-8"))
    ids = {e["id"] for e in db}
    new = [e for e in items if e["id"] not in ids]
    db.extend(new)
    db.sort(key=lambda e: e["date"])
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(db, f, ensure_ascii=False, indent=1)
    os.replace(tmp, path)
    print(f"{fname}: added={len(new)} skipped={len(items)-len(new)} -> {len(db)}条")
    total_added += len(new)
print(f"TOTAL added={total_added}")
