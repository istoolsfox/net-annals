# ── merge 到 2015-2019.json ─────────────────────────────────────────────
MAIN = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "data", "events", "2015-2019.json")
db = json.load(open(MAIN, encoding="utf-8"))
ids = {e["id"] for e in db}
new = [e for e in E if e["id"] not in ids]
skipped = len(E) - len(new)
db.extend(new)
db.sort(key=lambda e: e["date"])
tmp = MAIN + ".tmp"
with open(tmp, "w", encoding="utf-8") as f:
    json.dump(db, f, ensure_ascii=False, indent=1)
os.replace(tmp, MAIN)
print(f"added={len(new)} skipped={skipped} 文件现共 {len(db)} 条")
