def merge(path, batch):
    f = EV / path
    d = json.loads(f.read_text(encoding="utf-8"))
    have = {x["id"] for x in d}
    new = [x for x in batch if x["id"] not in have]
    d.extend(new)
    f.write_text(json.dumps(d, ensure_ascii=False, indent=0), encoding="utf-8")
    print(f"{path}: +{len(new)}（共 {len(d)}）")

