spans = {'2005-2009': [], '2010-2014': [], '2015-2019': [], '2020-2022': [], '2023-2026': []}
for e in E:
    y = int(e['date'][:4])
    for lo, hi in ((2005, 2009), (2010, 2014), (2015, 2019), (2020, 2022), (2023, 2026)):
        if lo <= y <= hi:
            spans[f'{lo}-{hi}'].append(e)
            break
for span, items in spans.items():
    out = f'data/events/.parts/gandong_{span}.json'
    json.dump(items, open(out, 'w'), ensure_ascii=False, indent=1)
    print(f'{span}: {len(items)} 条 → {out}')
