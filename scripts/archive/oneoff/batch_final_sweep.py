def merge(fn, batch, years=None):
    f = EV / fn
    d = json.loads(f.read_text(encoding="utf-8")) if f.exists() else []
    have = {x["id"] for x in d}
    add = [x for x in batch if x["id"] not in have and (years is None or x["date"][:4] in years)]
    d.extend(add)
    f.write_text(json.dumps(d, ensure_ascii=False, indent=0), encoding="utf-8")
    print(f"{fn}: +{len(add)}（共 {len(d)}）")

